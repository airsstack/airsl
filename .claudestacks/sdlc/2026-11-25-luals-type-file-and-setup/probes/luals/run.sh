#!/bin/sh
# Rebuilds every LuaLS fixture the spec cites and prints the command and result of each case.
# Usage: sh run.sh <empty-work-dir>   (LuaLS 3.19.2 from Mason)
set -u
LS="$HOME/.local/share/nvim/mason/bin/lua-language-server"
SELF_DIR="$(cd "$(dirname "$0")" && pwd)"; LAYOUT="$SELF_DIR/layout-typefile.lua"
W="$1"; rm -rf "$W"; mkdir -p "$W"; cd "$W" || exit 1
echo "LuaLS: $("$LS" --version)"
check() { # $1 = case dir
  echo "== $1"
  for f in .gitignore .luarc.json .luarc.jsonc; do [ -e "$1/$f" ] && printf '%s: %s\n' "$f" "$(tr '\n' ' ' < "$1/$f")"; done
  [ -d "$1/.git" ] && echo "(git repo)"
  echo "\$ cd $1 && lua-language-server --check . --checklevel=Information"
  (cd "$1" && "$LS" --check . --checklevel=Information --logpath="$W/log_$1" 2>&1) \
    | sed 's/\x1b\[[0-9;]*m//g' | tr '\r' '\n' \
    | grep -E '^[a-z_]+\.lua:[0-9]+:[0-9]+ \[|Diagnosis complete' | awk '!seen[$0]++'
}
header() { printf -- '---@meta\n-- Generated by airsl. Do not edit; regenerate it instead.\n\n---Host modules installed under `airsstack`.\n---@class airsstack\nairsstack = {}\n\n'; }
json_mod() { printf -- '---JSON encoding and decoding.\n---@class airsstack.json\nairsstack.json = {}\n\n---Encodes a value as compact JSON.\n---@param value any\n---@return string\nfunction airsstack.json.encode(value) end\n'; }
proj() { # $1 dir, $2 ignore|noignore ; writes type file with json module + main.lua using it
  mkdir -p "$1/.airsl/types"; (header; json_mod) > "$1/.airsl/types/airsstack.lua"
  (cd "$1" && git init -q . && [ "$2" = ignore ] && printf '.airsl/\n' > .gitignore)
  printf 'local s = airsstack.json.encode(1)\nlocal n = airsstack.json.nope\nprint(s, n)\n' > "$1/main.lua"
}
# --- luarc shapes, type dir gitignored so only the luarc can reveal it
proj control ignore
proj dotted ignore;   printf '{"workspace.library":[".airsl/types"]}' > dotted/.luarc.json
proj nested ignore;   printf '{"workspace":{"library":[".airsl/types"]}}' > nested/.luarc.json
proj comments ignore; printf '{\n  // keep me\n  "workspace.library": [".airsl/types"],\n}\n' > comments/.luarc.json
proj jsonc_only ignore; printf '{"workspace.library":[".airsl/types"]}' > jsonc_only/.luarc.jsonc
proj json_wins ignore;  printf '{"workspace.library":[".airsl/types"]}' > json_wins/.luarc.jsonc; printf '{"runtime.version":"Lua 5.4"}' > json_wins/.luarc.json
proj bom ignore;        printf '\357\273\277{"workspace.library":[".airsl/types"]}' > bom/.luarc.json
proj lastwins_has ignore;  printf '{"workspace.library":[], "workspace.library":[".airsl/types"]}' > lastwins_has/.luarc.json
proj firstwins_has ignore; printf '{"workspace.library":[".airsl/types"], "workspace.library":[]}' > firstwins_has/.luarc.json
proj nested_first_has ignore; printf '{"workspace":{"library":[".airsl/types"]}, "workspace.library":[]}' > nested_first_has/.luarc.json
proj dotted_first_has ignore; printf '{"workspace.library":[".airsl/types"], "workspace":{"library":[]}}' > dotted_first_has/.luarc.json
proj disjoint ignore; printf '{"workspace.library":[".airsl/types"], "workspace":{"checkThirdParty":false}}' > disjoint/.luarc.json
proj default_state noignore; printf '{"workspace.library":[".airsl/types"]}' > default_state/.luarc.json
for c in control dotted nested comments jsonc_only json_wins bom lastwins_has firstwins_has nested_first_has dotted_first_has disjoint default_state; do check $c; done
# --- type spellings
mkdir -p spell/.airsl/types; (cd spell && git init -q .)
printf '{"workspace.library":[".airsl/types"]}' > spell/.luarc.json
{ header; cat <<'LUA'
---Probe module.
---@class airsstack.t
airsstack.t = {}

---@param cb (fun(x: string): boolean)|string
function airsstack.t.funion_paren(cb) end

---@param cb fun(x: string): boolean|string
function airsstack.t.funion_bare(cb) end

---@param cb fun(a: string, b?: integer)
function airsstack.t.fun_optional_noreturn(cb) end

---@param xs (string?)[]
---@param fs (fun(x: string): boolean)[]
---@param ys string[]?
function airsstack.t.arrays(xs, fs, ys) end

---@param handler fun(payload: any): any
function airsstack.t.on(handler) end

---Says hi.
---@deprecated
function airsstack.t.old() end
LUA
} > spell/.airsl/types/airsstack.lua
cat > spell/use.lua <<'LUA'
airsstack.t.funion_paren("s")
airsstack.t.funion_paren(function(x) return x == "a" end)
airsstack.t.funion_bare("s")
airsstack.t.fun_optional_noreturn(function(a, b) return 1 end)
airsstack.t.arrays({ "a", nil }, { function(x) return true end }, nil)
airsstack.t.on(function(payload) return payload end)
airsstack.t.old()
LUA
check spell
# --- a required parameter after an optional one
mkdir -p order/.airsl/types; (cd order && git init -q .)
printf '{"workspace.library":[".airsl/types"]}' > order/.luarc.json
{ header; printf -- '---@class airsstack.t\nairsstack.t = {}\n\n---@param a? string\n---@param b integer\nfunction airsstack.t.f(a, b) end\n'; } > order/.airsl/types/airsstack.lua
printf 'airsstack.t.f(nil, 1)\nairsstack.t.f("x", 2)\nairsstack.t.f(nil, "no")\n' > order/use.lua
check order
# --- module field and reserved-word module, in the spec's file layout
mkdir -p layout/.airsl/types; (cd layout && git init -q . && printf '.airsl/\n' > .gitignore)
printf '{"workspace.library":[".airsl/types"]}' > layout/.luarc.json
cp "$LAYOUT" layout/.airsl/types/airsstack.lua
printf 'local v = airsstack.info.version:upper()\nlocal hi = airsstack["end"].hello("me"):upper()\nlocal a = airsstack.info.nope\nlocal b = airsstack["end"].nope\nprint(v, hi, a, b)\n' > layout/use.lua
check layout
# --- grammar: modules, records, literal unions, variadic, optional params, maps, record fun fields, reserved-word module
for g in grammar compose records; do
  mkdir -p $g/.airsl/types; (cd $g && git init -q . && printf '.airsl/\n' > .gitignore)
  printf '{"workspace.library":[".airsl/types"]}' > $g/.luarc.json
  cp "$SELF_DIR/$g-typefile.lua" $g/.airsl/types/airsstack.lua
  cp "$SELF_DIR/$g-good.lua" $g/good.lua; cp "$SELF_DIR/$g-bad.lua" $g/bad.lua
  check $g
done
