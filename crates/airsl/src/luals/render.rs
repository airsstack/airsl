//! The type file: turns the descriptions of a set of host modules into the text of a Lua language
//! server definition file.
//!
//! Its own module because the text is a contract with the editor, and a stray space or a doubled
//! blank line changes it. Keeping the layout in one pure function of the descriptions and the root
//! name makes the output byte-stable, which is what lets a caller tell that a rewrite would change
//! nothing.
//!
//! Responsibilities:
//!
//! - [`TypeFile`], the rendered text, the file name it belongs under and its accessors.
//! - The layout: the header, the root class, then per module its class and fields, its records and
//!   its functions, then `return <root>`, with every inline doc written after ` # ` so it stays
//!   doc text.
//! - Writing a module whose name is a Lua reserved word in bracket form.
//!
//! Non-responsibilities: writing the file anywhere, and checking that a description matches what a
//! module installs. The text holds no version, date or path.

use crate::description::{Field, Function, Member, Presence, Record};
use crate::error::Result;
use crate::modules::ModuleSet;
use crate::types::RootTable;
use crate::types::lua_name::RESERVED_WORDS;

use super::verify::describe_module;

/// The first block of every type file: marks it as a definition file and says not to edit it.
const HEADER: &str = "---@meta\n-- Generated by airsl. Do not edit; regenerate it instead.";

/// A rendered Lua language server type file for a set of host modules.
///
/// The text is a pure function of each module's description and the root table's name, so two
/// renders of the same set are byte-identical.
///
/// # Examples
///
/// ```
/// use airsl::description::{Function, LuaType, ModuleDescription};
/// use airsl::luals::TypeFile;
/// use airsl::{HostModule, InstallContext, ModuleName, ModuleSet, Result, RootTable};
///
/// struct Greeter(ModuleName);
///
/// impl HostModule for Greeter {
///     fn name(&self) -> &ModuleName {
///         &self.0
///     }
///
///     fn install(&self, _lua: &mlua::Lua, _table: &mlua::Table, _cx: &InstallContext<'_>) -> Result<()> {
///         Ok(())
///     }
///
///     fn describe(&self) -> Result<ModuleDescription> {
///         ModuleDescription::builder("Greetings.")
///             .function(Function::new("hello", "Says hello.").param("who", LuaType::STRING, "Who to greet."))
///             .build()
///     }
/// }
///
/// let mut modules = ModuleSet::new();
/// modules.insert(Box::new(Greeter(ModuleName::new("greeter")?)))?;
/// let file = TypeFile::render(&modules, &RootTable::default())?;
/// assert_eq!(file.file_name(), "airsstack.lua");
/// assert!(file.as_str().contains("function airsstack.greeter.hello(who) end"));
/// # Ok::<(), airsl::Error>(())
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeFile {
    root: String,
    text: String,
}

impl TypeFile {
    /// Renders the type file for `modules` under the root table `root`.
    ///
    /// Calls each module's `describe` in the set's insertion order. The file holds the header, the
    /// root class, and for every module its class with one field per described field, then one
    /// class per record, then one block per function. It ends by returning the root table, which
    /// is what lets the language server type `require("<root>")`.
    ///
    /// # Errors
    ///
    /// Returns [`Error::DescribeFailed`](crate::Error::DescribeFailed) when a module's `describe`
    /// fails, naming that module.
    pub fn render(modules: &ModuleSet, root: &RootTable) -> Result<Self> {
        let root_name = root.as_str();
        let mut blocks = vec![HEADER.to_owned(), root_block(root_name)];
        for module in modules.iter() {
            let description = describe_module(module)?;
            let name = module.name().as_str();
            let qualified = format!("{root_name}.{name}");
            let table = TablePath::new(root_name, name);

            let mut head = Vec::new();
            push_doc(&mut head, description.doc());
            head.push(format!("---@class {qualified}"));
            for member in description.members() {
                if let Member::Field(field) = member {
                    head.push(format!(
                        "---@field {} {}",
                        field.name(),
                        inline(&field.ty().spell(&qualified), field.doc())
                    ));
                }
            }
            head.push(format!("{} = {{}}", table.table));
            blocks.push(head.join("\n"));

            for record in description.records() {
                blocks.push(record_block(record, &qualified));
            }
            for member in description.members() {
                if let Member::Function(function) = member {
                    blocks.push(function_block(function, &qualified, &table));
                }
            }
        }
        blocks.push(format!("return {root_name}"));
        let mut text = blocks.join("\n\n");
        text.push('\n');
        Ok(Self {
            root: root_name.to_owned(),
            text,
        })
    }

    /// The name the file belongs under: the root table's name and `.lua`.
    #[must_use]
    pub fn file_name(&self) -> String {
        format!("{}.lua", self.root)
    }

    /// The text of the file.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.text
    }
}

/// How a module's table is written in the file: dotted, or bracketed when its name is a Lua
/// reserved word, which `<root>.end` would not parse as.
struct TablePath {
    table: String,
    bracketed: bool,
}

impl TablePath {
    fn new(root: &str, module: &str) -> Self {
        let bracketed = RESERVED_WORDS.contains(&module);
        let table = if bracketed {
            format!("{root}[\"{module}\"]")
        } else {
            format!("{root}.{module}")
        };
        Self { table, bracketed }
    }
}

fn root_block(root: &str) -> String {
    format!("---Host modules installed under `{root}`.\n---@class {root}\n{root} = {{}}")
}

/// Pushes one `---<line>` per line of `doc`, and nothing for an empty doc.
fn push_doc(lines: &mut Vec<String>, doc: &str) {
    if doc.is_empty() {
        return;
    }
    lines.extend(doc.split('\n').map(|line| format!("---{line}")));
}

/// A type followed by its doc after ` # `, or the type alone when there is no doc.
fn inline(ty: &str, doc: &str) -> String {
    if doc.is_empty() {
        ty.to_owned()
    } else {
        format!("{ty} # {doc}")
    }
}

fn record_block(record: &Record, prefix: &str) -> String {
    let mut lines = Vec::new();
    push_doc(&mut lines, record.doc());
    lines.push(format!("---@class {prefix}.{}", record.name()));
    for field in record.fields() {
        lines.push(record_field(field, prefix));
    }
    lines.join("\n")
}

fn record_field(field: &Field, prefix: &str) -> String {
    format!(
        "---@field {} {}",
        field.name(),
        inline(&field.ty().spell(prefix), field.doc())
    )
}

fn function_block(function: &Function, prefix: &str, table: &TablePath) -> String {
    let signature = function.signature();
    let mut lines = Vec::new();
    push_doc(&mut lines, function.doc());
    let mut names = Vec::new();
    for param in signature.params() {
        let mark = match param.presence() {
            Presence::Required => "",
            Presence::Optional => "?",
        };
        lines.push(format!(
            "---@param {}{mark} {}",
            param.name(),
            inline(&param.ty().spell(prefix), param.doc())
        ));
        names.push(param.name().to_owned());
    }
    if let Some(tail) = signature.variadic_type() {
        lines.push(format!(
            "---@param ... {}",
            inline(&tail.spell(prefix), function.variadic_doc())
        ));
        names.push("...".to_owned());
    }
    for ty in signature.returns_types() {
        lines.push(format!("---@return {}", ty.spell(prefix)));
    }
    let params = names.join(", ");
    let name = function.name();
    lines.push(if table.bracketed {
        format!("{}.{name} = function({params}) end", table.table)
    } else {
        format!("function {}.{name}({params}) end", table.table)
    });
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::unwrap_used,
        reason = "tests unwrap known-valid fixtures; a panic is the intended failure signal"
    )]

    use super::TypeFile;
    use crate::description::{Function, LuaType, ModuleDescription, Record};
    use crate::engine::Engine;
    use crate::error::{Error, Result};
    use crate::modules::{HostModule, InstallContext, ModuleSet, stdlib};
    use crate::sandbox::Policy;
    use crate::script::Script;
    use crate::types::{ModuleName, RootTable};

    /// A module that installs nothing and describes itself with a fixed result.
    struct Stub {
        name: ModuleName,
        description: Option<ModuleDescription>,
    }

    impl HostModule for Stub {
        fn name(&self) -> &ModuleName {
            &self.name
        }

        fn install(
            &self,
            _lua: &mlua::Lua,
            _table: &mlua::Table,
            _context: &InstallContext<'_>,
        ) -> Result<()> {
            Ok(())
        }

        fn describe(&self) -> Result<ModuleDescription> {
            self.description
                .clone()
                .ok_or_else(|| Error::InvalidDescription { reason: "x".into() })
        }
    }

    fn set_of(name: &str, description: Option<ModuleDescription>) -> ModuleSet {
        let mut set = ModuleSet::new();
        set.insert(Box::new(Stub {
            name: ModuleName::new(name).unwrap(),
            description,
        }))
        .unwrap();
        set
    }

    fn render_one(name: &str, description: ModuleDescription) -> String {
        TypeFile::render(&set_of(name, Some(description)), &RootTable::default())
            .unwrap()
            .as_str()
            .to_owned()
    }

    #[test]
    fn renders_the_header_and_root_class() {
        let file = TypeFile::render(&ModuleSet::new(), &RootTable::default()).unwrap();
        assert_eq!(
            file.as_str(),
            "---@meta\n\
             -- Generated by airsl. Do not edit; regenerate it instead.\n\
             \n\
             ---Host modules installed under `airsstack`.\n\
             ---@class airsstack\n\
             airsstack = {}\n\
             \n\
             return airsstack\n"
        );
    }

    #[test]
    fn renders_a_reserved_word_module_with_brackets() {
        let description = ModuleDescription::builder("A module whose name is a reserved word.")
            .function(
                Function::new("hello", "Says hi.")
                    .param("name", LuaType::STRING, "")
                    .returns(LuaType::STRING),
            )
            .build()
            .unwrap();
        let text = render_one("end", description);
        assert!(text.contains("---@class airsstack.end\nairsstack[\"end\"] = {}\n"));
        assert!(text.contains("airsstack[\"end\"].hello = function(name) end\n"));
        assert!(!text.contains("function airsstack.end"));
    }

    #[test]
    fn renders_module_fields_on_the_module_class() {
        let description = ModuleDescription::builder("Build facts.")
            .field("version", LuaType::STRING, "The host's version.")
            .build()
            .unwrap();
        let text = render_one("info", description);
        assert!(text.contains(
            "---Build facts.\n\
             ---@class airsstack.info\n\
             ---@field version string # The host's version.\n\
             airsstack.info = {}\n"
        ));
    }

    #[test]
    fn renders_optional_and_variadic_params() {
        let description = ModuleDescription::builder("Digests.")
            .function(
                Function::new("hash", "Hashes.")
                    .param("data", LuaType::STRING, "Bytes.")
                    .optional(
                        "algorithm",
                        LuaType::literal("sha256").or(LuaType::literal("sha1")),
                        "Defaults to sha256.",
                    )
                    .variadic(LuaType::STRING, ""),
            )
            .build()
            .unwrap();
        let text = render_one("hash", description);
        assert!(text.contains("---@param data string # Bytes.\n"));
        assert!(text.contains("---@param algorithm? \"sha256\"|\"sha1\" # Defaults to sha256.\n"));
        assert!(text.contains("---@param ... string\n"));
        assert!(text.contains("function airsstack.hash.hash(data, algorithm, ...) end\n"));
    }

    #[test]
    fn omits_empty_docs() {
        let description = ModuleDescription::builder("")
            .function(Function::new("f", "").param("x", LuaType::STRING, ""))
            .build()
            .unwrap();
        let text = render_one("m", description);
        assert!(text.ends_with(
            "---@class airsstack.m\n\
             airsstack.m = {}\n\
             \n\
             ---@param x string\n\
             function airsstack.m.f(x) end\n\
             \n\
             return airsstack\n"
        ));
        assert!(!text.contains('#'));
        assert!(text.lines().all(|line| line == line.trim_end()));
    }

    #[test]
    fn the_type_file_ends_by_returning_the_root() {
        let default = TypeFile::render(&stdlib().unwrap(), &RootTable::default()).unwrap();
        assert!(default.as_str().ends_with("\n\nreturn airsstack\n"));

        let root = RootTable::new("myapp").unwrap();
        let custom = TypeFile::render(&stdlib().unwrap(), &root).unwrap();
        assert!(custom.as_str().ends_with("\n\nreturn myapp\n"));
    }

    #[test]
    fn renders_multi_line_docs_one_line_each() {
        let description = ModuleDescription::builder("First.\nSecond.")
            .build()
            .unwrap();
        let text = render_one("m", description);
        assert!(text.contains("---First.\n---Second.\n---@class airsstack.m\n"));
    }

    #[test]
    fn inline_docs_follow_a_hash() {
        let description = ModuleDescription::builder("M.")
            .field("x", LuaType::STRING, "| none when unset")
            .build()
            .unwrap();
        let text = render_one("m", description);
        assert!(text.contains("---@field x string # | none when unset\n"));

        // An empty doc writes no `#`, on a module field, a record field and the variadic alike.
        let description = ModuleDescription::builder("M.")
            .field("y", LuaType::STRING, "")
            .function(Function::new("f", "").variadic(LuaType::STRING, "More text."))
            .function(Function::new("g", "").returns(LuaType::record("R")))
            .record(Record::new("R", "").field("z", LuaType::INTEGER, ""))
            .build()
            .unwrap();
        let text = render_one("m", description);
        assert!(text.contains("---@field y string\n"));
        assert!(text.contains("---@field z integer\n"));
        assert!(text.contains("---@param ... string # More text.\n"));
    }

    #[test]
    fn renders_modules_in_insertion_order() {
        let mut set = ModuleSet::new();
        for name in ["zeta", "alpha"] {
            set.insert(Box::new(Stub {
                name: ModuleName::new(name).unwrap(),
                description: Some(ModuleDescription::builder("").build().unwrap()),
            }))
            .unwrap();
        }
        let file = TypeFile::render(&set, &RootTable::default()).unwrap();
        let text = file.as_str();
        let zeta = text.find("---@class airsstack.zeta\n").unwrap();
        let alpha = text.find("---@class airsstack.alpha\n").unwrap();
        assert!(zeta < alpha);
    }

    #[test]
    fn renders_multiple_returns() {
        let description = ModuleDescription::builder("M.")
            .function(
                Function::new("f", "")
                    .returns(LuaType::STRING)
                    .returns(LuaType::INTEGER),
            )
            .build()
            .unwrap();
        let text = render_one("m", description);
        assert!(
            text.contains("---@return string\n---@return integer\nfunction airsstack.m.f() end\n")
        );
    }

    #[test]
    fn renders_records_before_functions() {
        let description = ModuleDescription::builder("M.")
            .function(Function::new("f", "Gets.").returns(LuaType::record("Out")))
            .record(Record::new("Out", "Output.").field("n", LuaType::INTEGER, "A count."))
            .build()
            .unwrap();
        let text = render_one("m", description);
        let record = text.find("---@class airsstack.m.Out\n").unwrap();
        let function = text.find("function airsstack.m.f()").unwrap();
        assert!(record < function);
        assert!(
            text.contains(
                "---Output.\n---@class airsstack.m.Out\n---@field n integer # A count.\n"
            )
        );
        assert!(text.contains("---@return airsstack.m.Out\n"));
    }

    #[test]
    fn the_stdlib_type_file_compiles_as_lua() {
        let file = TypeFile::render(&stdlib().unwrap(), &RootTable::default()).unwrap();
        let engine = Engine::builder().policy(Policy::pure()).build().unwrap();
        let script = Script::from_source(file.as_str(), "airsstack.lua").unwrap();
        engine.check(&script).unwrap();
    }

    #[test]
    fn rendering_twice_is_byte_identical() {
        let root = RootTable::default();
        let first = TypeFile::render(&stdlib().unwrap(), &root).unwrap();
        let second = TypeFile::render(&stdlib().unwrap(), &root).unwrap();
        assert_eq!(first, second);
    }

    #[test]
    fn a_host_root_names_the_file_and_classes() {
        let root = RootTable::new("agentstacks").unwrap();
        let file = TypeFile::render(&stdlib().unwrap(), &root).unwrap();
        assert_eq!(file.file_name(), "agentstacks.lua");
        assert!(file.as_str().contains("---@class agentstacks.json"));
        assert!(!file.as_str().contains("airsstack"));
    }

    #[test]
    fn a_describe_error_names_the_module() {
        let error = TypeFile::render(&set_of("stub", None), &RootTable::default()).unwrap_err();
        assert_eq!(
            error.to_string(),
            "cannot describe host module `stub`: invalid module description: x"
        );
    }
}
